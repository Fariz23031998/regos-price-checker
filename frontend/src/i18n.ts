const dictionaries: Record<Language, Record<MessageKey, string>> = { uz, ru, en };

export const LANGUAGE_OPTIONS: Array<{ value: Language; label: string }> = [
  { value: "uz", label: "Oʻzbekcha" },
  { value: "ru", label: "Русский" },
  { value: "en", label: "English" },
];

export function asLanguage(value: unknown): Language {
  return value === "uz" || value === "en" ? value : "ru";
}

export function t(
  language: string | undefined,
  key: MessageKey,
  vars?: Record<string, string | number>,
): string {
  const code: Language = language === "uz" || language === "en" ? language : "ru";
  let text = dictionaries[code][key];
  if (!vars) return text;
  for (const [name, value] of Object.entries(vars)) {
    text = text.replaceAll(`{${name}}`, String(value));
  }
  return text;
}
